import { useAuth } from "@/_core/hooks/useAuth";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Textarea } from "@/components/ui/textarea";
import { trpc } from "@/lib/trpc";
import { Leaf, Loader2, Download } from "lucide-react";
import { useState } from "react";
import { Link } from "wouter";
import { toast } from "sonner";

const CROPS = [
  "Boro Rice",
  "T. Aman Rice",
  "Wheat",
  "Potato",
  "Mungbean",
];

const SEASONS = ["Kharif", "Rabi", "Zaid"];

export default function Fertilizer() {
  const { user } = useAuth();
  const [selectedField, setSelectedField] = useState<number | null>(null);
  const [selectedCrop, setSelectedCrop] = useState<string>("");
  const [season, setSeason] = useState<string>("");
  const [yieldGoal, setYieldGoal] = useState<string>("");
  const [recommendation, setRecommendation] = useState<any>(null);

  const fieldsQuery = trpc.fields.list.useQuery();
  const fertilizerDataQuery = trpc.fertilizer.getRecommendationData.useQuery(
    { cropName: selectedCrop },
    { enabled: !!selectedCrop }
  );
  const createRecommendationMutation = trpc.fertilizer.create.useMutation({
    onSuccess: () => {
      toast.success("Fertilizer recommendation saved!");
      setSelectedCrop("");
      setSeason("");
      setYieldGoal("");
      setRecommendation(null);
    },
    onError: (error) => {
      toast.error("Failed to save recommendation: " + error.message);
    },
  });

  const handleGetRecommendation = () => {
    if (!selectedField || !selectedCrop || !yieldGoal) {
      toast.error("Please select field, crop, and yield goal");
      return;
    }

    const data = fertilizerDataQuery.data;
    if (!data) {
      toast.error("No recommendation data available for this crop");
      return;
    }

    const yieldData = data.yieldGoals[yieldGoal as keyof typeof data.yieldGoals];
    if (!yieldData) {
      toast.error("Invalid yield goal");
      return;
    }

    setRecommendation({
      crop: selectedCrop,
      season,
      yieldGoal,
      npk: yieldData,
      micronutrients: data.micronutrients,
      organicFertilizer: data.organicFertilizer,
      chemicalFertilizer: data.chemicalFertilizer,
      bioFertilizer: data.bioFertilizer,
      limingRecommendation: data.limingRecommendation,
      applicationSchedule: data.applicationSchedule,
    });
  };

  const handleSaveRecommendation = () => {
    if (!selectedField || !recommendation) {
      toast.error("Please generate a recommendation first");
      return;
    }

    createRecommendationMutation.mutate({
      fieldId: selectedField,
      cropName: selectedCrop,
      season: season || undefined,
      yieldGoal,
      recommendationSource: "FRG 2024",
      confidenceLevel: "High",
      npkRecommendation: JSON.stringify(recommendation.npk),
      micronutrients: JSON.stringify(recommendation.micronutrients),
      organicFertilizer: recommendation.organicFertilizer,
      chemicalFertilizer: recommendation.chemicalFertilizer,
      bioFertilizer: recommendation.bioFertilizer,
      limingRecommendation: recommendation.limingRecommendation,
      applicationSchedule: recommendation.applicationSchedule,
    });
  };

  const handleDownloadPDF = () => {
    if (!recommendation) return;
    
    const content = `
FERTILIZER RECOMMENDATION REPORT
Generated by Precision Khamari
Date: ${new Date().toLocaleDateString()}

CROP INFORMATION
Crop: ${recommendation.crop}
Season: ${recommendation.season || "Not specified"}
Yield Goal: ${recommendation.yieldGoal}

NPK RECOMMENDATION (kg/ha)
Nitrogen (N): ${recommendation.npk.N} kg/ha
Phosphorus (P): ${recommendation.npk.P} kg/ha
Potassium (K): ${recommendation.npk.K} kg/ha

MICRONUTRIENTS
${Object.entries(recommendation.micronutrients)
  .map(([key, value]) => `${key}: ${value}`)
  .join("\n")}

ORGANIC FERTILIZER
${recommendation.organicFertilizer}

CHEMICAL FERTILIZER
${recommendation.chemicalFertilizer}

BIO-FERTILIZER
${recommendation.bioFertilizer}

LIMING RECOMMENDATION
${recommendation.limingRecommendation}

APPLICATION SCHEDULE
${recommendation.applicationSchedule}

Note: This recommendation is based on FRG 2024 and should be adjusted based on actual soil test results.
    `;

    const element = document.createElement("a");
    element.setAttribute("href", "data:text/plain;charset=utf-8," + encodeURIComponent(content));
    element.setAttribute("download", `fertilizer-recommendation-${selectedCrop}.txt`);
    element.style.display = "none";
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="min-h-screen bg-gray-50">
      <nav className="bg-white shadow-sm sticky top-0 z-50">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-4 flex justify-between items-center">
          <Link href="/">
            <div className="flex items-center gap-2 cursor-pointer">
              <Leaf className="w-8 h-8 text-green-600" />
              <h1 className="text-2xl font-bold text-gray-900">Precision Khamari</h1>
            </div>
          </Link>
        </div>
      </nav>

      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-12">
        <div className="mb-8">
          <h2 className="text-3xl font-bold text-gray-900 mb-2">Fertilizer Recommendation Engine</h2>
          <p className="text-gray-600">Get FRG 2024 based NPK and micronutrient recommendations for your crops</p>
        </div>

        <div className="grid lg:grid-cols-3 gap-8">
          {/* Input Section */}
          <div className="lg:col-span-2">
            <Card>
              <CardHeader>
                <CardTitle>Generate Recommendation</CardTitle>
                <CardDescription>Select your field and crop to get fertilizer guidance</CardDescription>
              </CardHeader>
              <CardContent className="space-y-6">
                {/* Field Selection */}
                <div>
                  <Label htmlFor="field">Select Field *</Label>
                  <Select value={selectedField?.toString() || ""} onValueChange={(v) => setSelectedField(parseInt(v))}>
                    <SelectTrigger>
                      <SelectValue placeholder="Choose a field" />
                    </SelectTrigger>
                    <SelectContent>
                      {fieldsQuery.data?.map((field) => (
                        <SelectItem key={field.id} value={field.id.toString()}>
                          {field.fieldName} ({field.areaInBigha} Bigha)
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>

                {/* Crop Selection */}
                <div>
                  <Label htmlFor="crop">Select Crop *</Label>
                  <Select value={selectedCrop} onValueChange={setSelectedCrop}>
                    <SelectTrigger>
                      <SelectValue placeholder="Choose a crop" />
                    </SelectTrigger>
                    <SelectContent>
                      {CROPS.map((crop) => (
                        <SelectItem key={crop} value={crop}>
                          {crop}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>

                {/* Season Selection */}
                <div>
                  <Label htmlFor="season">Season</Label>
                  <Select value={season} onValueChange={setSeason}>
                    <SelectTrigger>
                      <SelectValue placeholder="Choose season (optional)" />
                    </SelectTrigger>
                    <SelectContent>
                      {SEASONS.map((s) => (
                        <SelectItem key={s} value={s}>
                          {s}
                        </SelectItem>
                      ))}
                    </SelectContent>
                  </Select>
                </div>

                {/* Yield Goal Selection */}
                {selectedCrop && fertilizerDataQuery.data && (
                  <div>
                    <Label htmlFor="yieldGoal">Yield Goal *</Label>
                    <Select value={yieldGoal} onValueChange={setYieldGoal}>
                      <SelectTrigger>
                        <SelectValue placeholder="Choose yield goal" />
                      </SelectTrigger>
                      <SelectContent>
                        {Object.keys(fertilizerDataQuery.data.yieldGoals).map((goal) => (
                          <SelectItem key={goal} value={goal}>
                            {goal}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  </div>
                )}

                <Button
                  onClick={handleGetRecommendation}
                  disabled={fertilizerDataQuery.isLoading || !selectedField || !selectedCrop || !yieldGoal}
                  className="w-full bg-green-600 hover:bg-green-700"
                >
                  {fertilizerDataQuery.isLoading ? (
                    <>
                      <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                      Loading...
                    </>
                  ) : (
                    "Generate Recommendation"
                  )}
                </Button>
              </CardContent>
            </Card>
          </div>

          {/* Recommendation Display */}
          <div className="space-y-6">
            {recommendation && (
              <>
                <Card className="border-green-200 bg-green-50">
                  <CardHeader>
                    <CardTitle className="text-green-900">NPK Recommendation</CardTitle>
                  </CardHeader>
                  <CardContent className="space-y-3">
                    <div className="grid grid-cols-3 gap-2">
                      <div className="bg-white p-3 rounded border border-green-200">
                        <p className="text-xs text-gray-600">Nitrogen</p>
                        <p className="text-lg font-bold text-green-700">{recommendation.npk.N}</p>
                        <p className="text-xs text-gray-600">kg/ha</p>
                      </div>
                      <div className="bg-white p-3 rounded border border-green-200">
                        <p className="text-xs text-gray-600">Phosphorus</p>
                        <p className="text-lg font-bold text-green-700">{recommendation.npk.P}</p>
                        <p className="text-xs text-gray-600">kg/ha</p>
                      </div>
                      <div className="bg-white p-3 rounded border border-green-200">
                        <p className="text-xs text-gray-600">Potassium</p>
                        <p className="text-lg font-bold text-green-700">{recommendation.npk.K}</p>
                        <p className="text-xs text-gray-600">kg/ha</p>
                      </div>
                    </div>
                  </CardContent>
                </Card>

                <Card>
                  <CardHeader>
                    <CardTitle className="text-base">Micronutrients</CardTitle>
                  </CardHeader>
                  <CardContent className="space-y-2 text-sm">
                    {Object.entries(recommendation.micronutrients).map(([key, value]) => (
                      <div key={key} className="flex justify-between">
                        <span className="text-gray-600">{key}:</span>
                        <span className="font-semibold">{value as string}</span>
                      </div>
                    ))}
                  </CardContent>
                </Card>

                <Card>
                  <CardHeader>
                    <CardTitle className="text-base">Application Details</CardTitle>
                  </CardHeader>
                  <CardContent className="space-y-3 text-sm">
                    <div>
                      <p className="font-semibold text-gray-900 mb-1">Organic Fertilizer:</p>
                      <p className="text-gray-600">{recommendation.organicFertilizer}</p>
                    </div>
                    <div>
                      <p className="font-semibold text-gray-900 mb-1">Bio-Fertilizer:</p>
                      <p className="text-gray-600">{recommendation.bioFertilizer}</p>
                    </div>
                    {recommendation.limingRecommendation && (
                      <div>
                        <p className="font-semibold text-gray-900 mb-1">Liming:</p>
                        <p className="text-gray-600">{recommendation.limingRecommendation}</p>
                      </div>
                    )}
                  </CardContent>
                </Card>

                <div className="flex gap-2">
                  <Button
                    onClick={handleSaveRecommendation}
                    disabled={createRecommendationMutation.isPending}
                    className="flex-1 bg-green-600 hover:bg-green-700"
                  >
                    {createRecommendationMutation.isPending ? (
                      <>
                        <Loader2 className="w-4 h-4 mr-2 animate-spin" />
                        Saving...
                      </>
                    ) : (
                      "Save Recommendation"
                    )}
                  </Button>
                  <Button
                    onClick={handleDownloadPDF}
                    variant="outline"
                  >
                    <Download className="w-4 h-4 mr-2" />
                    Download
                  </Button>
                </div>
              </>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
